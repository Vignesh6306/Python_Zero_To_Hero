# Integers : A numbers from postive to negative without decimal point

print(10)
print(-2)

# Float : A numbers from positive to negative with decimal point and e -> express 10

print(3.33)
print(-2.0)
print(4e6)

# Complex : Real part and Imaginary part. Represent as J

print(10j)
print(2 + 10j)
print(-5j)

# String : Sequence of character surrounded by quotes " or '

print("Hello hi")
print('Hello bye')

# Type() : To know which datatypes are present

print(type(10))
print(type(2.0))
print(type(2j))
print(type(2e6))
print(type('Hello'))

# Boolean : Return True or False

print(True)
print(type(False))

# None : Nothing is presence

print(None)
print(type(None))