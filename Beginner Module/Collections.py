# List : Mutable(Changeable) and Surrounded by []
List = [10,20,30,40,50]
print(List)
print(type(List))

# Tuples : Immutable(Unchangeable) and Surrounded by ()
T = (1,2,3,4,5)
print(T)
print(type(T))

# Set : Mutable(Changeable), Unordered, Avoid Duplicate and Surrounded by {}
S1 = {2,4,6,8,10}
S2 = {1,2,3,1,2,3}
print(S1)
print(S2)
print(type(S1))

# Dictionary : Key-Value pair and Surrounded by {}
D = {
    'Name' : 'Vicky',
    'Age' : 10
}
print(D)
print(type(D))


