A = "meThoDs oF sTriNgS"
# Capitalize : Converts the first letter into capital
print(A.capitalize())

# Casefold : Similar to lower case. But more aggressive
print(A.casefold())

# Title : Converts the First letter in the sequence as Capital
print(A.title())

# Lower : Coverts everything into Lower-case
print(A.lower())

# Lower : Coverts everything into Upper-case
print(A.upper())

# SwapCase : Coverts Lower into Upper And Upper into Lower vice versa
print(A.swapcase())



